"""Generate the GM-041 sample evaluation from an archived evidence bundle.

**The output is a SYNTHETIC, NON-PRODUCTION demonstration.** No production model
configuration exists — Q11 through Q16 remain open Product Owner decisions — so
this runs the real engine over real archived snapshots under a loudly disclaimed
synthetic configuration whose numbers are deliberately wrong for baseball. The
scores below demonstrate that the engine executes and explains itself. They say
nothing about the hitter.

GreenMachine intentionally separates evaluation from decision-making. The
document this writes contains exactly the engine's six outputs — Total Score,
Tier, Component Breakdown, Audit Trail, Warnings, and Fallbacks — and nothing
resembling advice.

Deterministic: no clock, no network, no randomness. The evidence bundle is read
and never written. Rerunning with the same inputs produces byte-identical
output.

Usage::

    python scripts/generate_gm041_sample_evaluation.py
    python scripts/generate_gm041_sample_evaluation.py --run-dir DIR --output DIR

Exit codes: 0 ok · 2 typed error.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]

if str(_REPO_ROOT / "src") not in sys.path:  # pragma: no cover - script bootstrap
    sys.path.insert(0, str(_REPO_ROOT / "src"))

from greenmachine.common.errors import GreenMachineError  # noqa: E402
from greenmachine.common.serialization import canonical_bytes  # noqa: E402
from greenmachine.config import GreenMachineConfig, load_config  # noqa: E402
from greenmachine.domain import EvaluatedGradeResult, InputSnapshot  # noqa: E402
from greenmachine.evaluation import deserialize_snapshot  # noqa: E402
from greenmachine.scoring import score_snapshot  # noqa: E402

DEFAULT_RUN_DIR = _REPO_ROOT / "evidence" / "gm020_vertical_slice" / "run_gm040_ohtani"
DEFAULT_CONFIG = _REPO_ROOT / "config" / "nonproduction" / "gm041_engine_synthetic.yaml"
DEFAULT_OUTPUT = _REPO_ROOT / "docs" / "samples"

SNAPSHOT_FILES = ("input_snapshot_recent_7d.json", "input_snapshot_long_term_2y.json")

# The engine's entire analytical output for an EVALUATED profile. A test asserts
# this exact set, so a seventh key is a scope change rather than a detail.
EVALUATED_KEYS = frozenset(
    {
        "total_score",
        "tier",
        "component_breakdown",
        "audit_trail",
        "warnings",
        "fallbacks",
    }
)

# Provenance about the sample itself — what was scored, under which
# configuration, and the disclaimer. Metadata, never an engine output.
METADATA_KEYS = frozenset(
    {
        "disclaimer",
        "evidence_bundle",
        "model_configuration_version",
        "specification_version",
    }
)

DISCLAIMER = (
    "SYNTHETIC, NON-PRODUCTION SAMPLE. Generated by the real GM-041 engine over "
    "real archived snapshots, under a deliberately wrong-for-baseball synthetic "
    "configuration. No production model configuration exists (Q11-Q16 remain open "
    "Product Owner decisions). These numbers demonstrate that the engine executes "
    "and explains itself; they say nothing about the hitter. GreenMachine "
    "separates evaluation from decision-making and never advises."
)


def _component_breakdown(result: EvaluatedGradeResult) -> dict[str, object]:
    """Per-category and per-component scores, in the engine's own order."""
    return {
        "categories": [
            {
                "category": category.category.value,
                "points_awarded": category.points_awarded,
                "components": [
                    {
                        "component_id": score.component_id.value,
                        "measurement_id": (
                            score.measurement_id.value if score.measurement_id else None
                        ),
                        "points_awarded": score.points_awarded,
                        "bucket": (
                            None
                            if score.bucket_hit is None
                            else {
                                "lower_bound": score.bucket_hit.lower_bound,
                                "upper_bound": score.bucket_hit.upper_bound,
                                "is_terminal": score.bucket_hit.is_terminal,
                            }
                        ),
                    }
                    for score in category.component_scores
                ],
            }
            for category in result.category_scores
        ]
    }


def _fallbacks(snapshot: InputSnapshot) -> list[dict[str, object]]:
    """Provenance of every fallback the ingestion layer actually recorded."""
    entries: list[dict[str, object]] = []
    for observation in snapshot.present_observations:
        fallback = observation.fallback_used
        if fallback is None:
            continue
        entries.append(
            {
                "component_id": observation.component_id.value,
                "acquisition_method": observation.acquisition_method.value,
                "higher_priority_ineligible": [
                    {"method": record.method.value, "reason": record.reason}
                    for record in fallback.higher_priority_ineligible
                ],
            }
        )
    return entries


def _profile_document(snapshot: InputSnapshot, config: GreenMachineConfig) -> dict[str, object]:
    """Exactly the six approved engine outputs for one window profile."""
    result = score_snapshot(snapshot, config)
    audit_trail = [
        {
            "sequence": entry.sequence,
            "stage": entry.stage,
            "component_id": entry.component_id.value if entry.component_id else None,
            "category": entry.category.value if entry.category else None,
            "rule_reference": entry.rule_reference,
            "input_summary": entry.input_summary,
            "output_summary": entry.output_summary,
            "explanation": entry.explanation,
        }
        for entry in result.audit_derivation
    ]
    warnings = [
        {
            "input_id": finding.input_id.value,
            "component_id": finding.component_id.value if finding.component_id else None,
            "message": finding.message,
        }
        for finding in result.validation_findings
    ]

    if not isinstance(result, EvaluatedGradeResult):
        # NOT_EVALUABLE is a distinct terminal state, never a low grade. It is
        # not an evaluated profile, so the six-output contract does not apply;
        # it reports which required inputs were unavailable instead.
        return {
            "evaluation_status": result.status.value,
            "unavailable_required_inputs": [
                {
                    "component_id": entry.component_id.value,
                    "missing_reason": entry.missing_reason.value,
                }
                for entry in result.unavailable_required_inputs
            ],
            "audit_trail": audit_trail,
            "warnings": warnings,
            "fallbacks": _fallbacks(snapshot),
        }

    # Exactly the six approved engine outputs, and nothing else. EVALUATED_KEYS
    # is the contract a test asserts against; adding a seventh key here is a
    # deliberate scope change, not an implementation detail.
    return {
        "total_score": result.total_score,
        "tier": result.grade.value,
        "component_breakdown": _component_breakdown(result),
        "audit_trail": audit_trail,
        "warnings": warnings,
        "fallbacks": _fallbacks(snapshot),
    }


def build_document(run_dir: Path, config: GreenMachineConfig) -> dict[str, object]:
    """The sample document: metadata about the sample, plus one entry per profile.

    The four top-level keys beside ``profiles`` are **sample provenance
    metadata** — what was scored, under which configuration, and the
    disclaimer. They are not engine outputs. The engine's outputs are exactly
    the six keys of :data:`EVALUATED_KEYS`, which appear inside each evaluated
    profile.
    """
    profiles: dict[str, object] = {}
    for filename in SNAPSHOT_FILES:
        snapshot = deserialize_snapshot((run_dir / "snapshots" / filename).read_bytes())
        profiles[snapshot.window_profile.value] = _profile_document(snapshot, config)
    return {
        "disclaimer": DISCLAIMER,
        "evidence_bundle": run_dir.name,
        "model_configuration_version": config.model_configuration_version,
        "specification_version": config.specification_version,
        "profiles": profiles,
    }


def _render_markdown(document: dict[str, object]) -> str:
    profiles = document["profiles"]
    assert isinstance(profiles, dict)
    lines = [
        "# GM-041 sample evaluation — SYNTHETIC, NON-PRODUCTION",
        "",
        f"> **{document['disclaimer']}**",
        "",
        f"- Evidence bundle: `{document['evidence_bundle']}`",
        f"- Model configuration: `{document['model_configuration_version']}` "
        f"(specification `{document['specification_version']}`)",
        "",
        "The engine's entire output is Total Score, Tier, Component Breakdown, "
        "Audit Trail, Warnings, and Fallbacks. There is no automated "
        "recommendation and no decision output of any kind, and there never "
        "will be.",
        "",
    ]
    for profile_name in sorted(profiles):
        profile = profiles[profile_name]
        assert isinstance(profile, dict)
        lines += [f"## {profile_name}", ""]
        if "total_score" not in profile:
            lines += [f"Evaluation status: **{profile['evaluation_status']}**", ""]
            continue
        lines += [
            f"- **Total Score:** {profile['total_score']}",
            f"- **Tier:** {profile['tier']}",
            "",
            "### Component Breakdown",
            "",
            "| Category | Category points | Component | Component points |",
            "|---|---|---|---|",
        ]
        breakdown = profile["component_breakdown"]
        assert isinstance(breakdown, dict)
        categories = breakdown["categories"]
        assert isinstance(categories, list)
        for category in categories:
            assert isinstance(category, dict)
            components = category["components"]
            assert isinstance(components, list)
            for index, component in enumerate(components):
                assert isinstance(component, dict)
                name = category["category"] if index == 0 else ""
                points = category["points_awarded"] if index == 0 else ""
                lines.append(
                    f"| {name} | {points} | `{component['component_id']}` | "
                    f"{component['points_awarded']} |"
                )
        audit = profile["audit_trail"]
        assert isinstance(audit, list)
        warnings = profile["warnings"]
        assert isinstance(warnings, list)
        fallbacks = profile["fallbacks"]
        assert isinstance(fallbacks, list)
        lines += [
            "",
            "### Audit Trail",
            "",
            f"{len(audit)} ordered entries; the machine-readable form is in the "
            "accompanying JSON. Stages, in order:",
            "",
        ]
        for entry in audit:
            assert isinstance(entry, dict)
            lines.append(f"{entry['sequence']}. `{entry['stage']}` — {entry['output_summary']}")
        lines += [
            "",
            "### Warnings",
            "",
            "None." if not warnings else "",
        ]
        for warning in warnings:
            assert isinstance(warning, dict)
            lines.append(f"- `{warning['component_id']}`: {warning['message']}")
        lines += ["", "### Fallbacks", "", "None." if not fallbacks else ""]
        for fallback in fallbacks:
            assert isinstance(fallback, dict)
            lines.append(f"- `{fallback['component_id']}` via `{fallback['acquisition_method']}`")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _display_path(path: Path) -> str:
    """Repository-relative when possible, otherwise the resolved absolute path.

    ``--output`` may point anywhere, including another drive, so
    ``Path.relative_to`` is not guaranteed to succeed and must never be the
    reason a successful generation reports failure.
    """
    resolved = path.resolve()
    try:
        return resolved.relative_to(_REPO_ROOT).as_posix()
    except ValueError:
        return resolved.as_posix()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", type=Path, default=DEFAULT_RUN_DIR)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    arguments = parser.parse_args(argv)

    try:
        config = load_config(arguments.config)
        document = build_document(arguments.run_dir, config)
    except GreenMachineError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    arguments.output.mkdir(parents=True, exist_ok=True)
    json_path = arguments.output / "gm041_sample_evaluation.json"
    markdown_path = arguments.output / "gm041_sample_evaluation.md"
    json_path.write_bytes(canonical_bytes(document))
    markdown_path.write_text(_render_markdown(document), encoding="utf-8", newline="\n")

    print(f"wrote {_display_path(json_path)}")
    print(f"wrote {_display_path(markdown_path)}")
    return 0


if __name__ == "__main__":  # pragma: no cover - script entry point
    raise SystemExit(main())
